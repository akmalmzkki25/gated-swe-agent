"""Rebuild every reported number from committed files only (no API key, no Docker).

Inputs: eval/<who>/<split>/seed<k>/resolved.json (harness verdicts) and the trajectories in
runs/<who>/<split>/seed<k>/. Outputs: results/per_task.csv and results/summary.md.
"""

from __future__ import annotations

import csv
import glob
import json
from math import comb
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SEEDS = (0, 1, 2)
WHO = ("baseline", "agent")
SPLITS = ("eval", "dev", "dev_hard")


def pass_at_1(table: dict[str, list[bool]]) -> float:
    runs = [ok for seeds in table.values() for ok in seeds]
    return sum(runs) / len(runs)


def pass_at_k(table: dict[str, list[bool]]) -> float:
    return sum(any(seeds) for seeds in table.values()) / len(table)


def sign_test(wins: int, losses: int) -> float:
    """Exact two-sided sign test on discordant pairs."""
    n = wins + losses
    if n == 0:
        return 1.0
    tail = sum(comb(n, i) for i in range(min(wins, losses) + 1)) / 2**n
    return min(1.0, 2 * tail)


def _run_info(who: str, split: str, seed: int, iid: str) -> dict:
    paths = glob.glob(str(ROOT / f"runs/{who}/{split}/seed{seed}/{iid}/*.traj.json"))
    if not paths:
        return {}
    info = json.loads(Path(paths[0]).read_text(encoding="utf-8"))["info"]
    if who == "baseline":
        stats = info.get("model_stats", {})
        return {"calls": stats.get("api_calls"), "cost": stats.get("instance_cost"), "exit": info.get("exit_status")}
    return {"calls": info.get("n_calls"), "cost": info.get("cost"), "exit": info.get("exit_status"), "version": info.get("agent_version")}


def load(split: str) -> dict[str, dict[str, list[bool]]] | None:
    ids = [json.loads(line)["instance_id"] for line in (ROOT / f"data/{split}/test.jsonl").read_text(encoding="utf-8").splitlines()]
    tables = {}
    for who in WHO:
        files = [ROOT / f"eval/{who}/{split}/seed{s}/resolved.json" for s in SEEDS]
        if not all(f.exists() for f in files):
            return None
        verdicts = [json.loads(f.read_text(encoding="utf-8")) for f in files]
        tables[who] = {iid: [bool(v.get(iid, False)) for v in verdicts] for iid in ids}
    return tables


def main() -> None:
    rows, lines = [], ["# Summary (generated by `track3 report`; do not edit by hand)", ""]
    for split in SPLITS:
        tables = load(split)
        if tables is None:
            continue
        base, agent = tables["baseline"], tables["agent"]
        wins = sum(1 for t in base for s in range(len(SEEDS)) if agent[t][s] and not base[t][s])
        losses = sum(1 for t in base for s in range(len(SEEDS)) if base[t][s] and not agent[t][s])
        cost = {who: sum((_run_info(who, split, s, t).get("cost") or 0) for t in base for s in SEEDS) for who in WHO}
        b1, a1 = pass_at_1(base), pass_at_1(agent)
        lines += [
            f"## {split} ({len(base)} tasks x {len(SEEDS)} seeds)" + ("  <- reported result" if split == "eval" else "  (development)"),
            "",
            "| | baseline (mini-swe-agent) | gated agent |",
            "|---|---|---|",
            f"| pass@1 | {b1:.1%} | {a1:.1%} |",
            f"| pass@3 | {pass_at_k(base):.1%} | {pass_at_k(agent):.1%} |",
            f"| resolved per seed | {' / '.join(str(sum(base[t][s] for t in base)) for s in range(len(SEEDS)))} "
            f"| {' / '.join(str(sum(agent[t][s] for t in agent)) for s in range(len(SEEDS)))} |",
            f"| cost | ${cost['baseline']:.2f} | ${cost['agent']:.2f} |",
            "",
            f"Lift (pass@1): **{(a1 - b1) * 100:+.1f} pts**. Paired task x seed: agent wins {wins}, "
            f"loses {losses}; exact two-sided sign test p = {sign_test(wins, losses):.3f}.",
            "",
        ]
        for t in base:
            for s in SEEDS:
                for who in WHO:
                    info = _run_info(who, split, s, t)
                    rows.append({"split": split, "task": t, "seed": s, "agent": who, "resolved": tables[who][t][s], **info})
    with (ROOT / "results/per_task.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(
            f, fieldnames=["split", "task", "seed", "agent", "resolved", "calls", "cost", "exit", "version"], lineterminator="\n"
        )
        w.writeheader()
        w.writerows(rows)
    (ROOT / "results/summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
